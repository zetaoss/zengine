CREATE TABLE IF NOT EXISTS doc_evaluations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  page_id INT UNSIGNED NOT NULL,
  page_title VARCHAR(255) NOT NULL,
  revid BIGINT UNSIGNED NOT NULL DEFAULT 0,
  grade CHAR(1) NOT NULL,
  general_quality TINYINT UNSIGNED NOT NULL,
  text_quality TINYINT UNSIGNED NOT NULL,
  safety_violated TINYINT(1) NOT NULL DEFAULT 0,
  safety_policies VARCHAR(255) NOT NULL DEFAULT '',
  accuracy_contradicted INT UNSIGNED NOT NULL DEFAULT 0,
  summary VARCHAR(500) NOT NULL,
  rubrics LONGTEXT NOT NULL,
  chain_version VARCHAR(16) NOT NULL,
  raw_json LONGTEXT NOT NULL,
  model VARCHAR(128) NOT NULL,
  prompt_tokens INT UNSIGNED NOT NULL DEFAULT 0,
  completion_tokens INT UNSIGNED NOT NULL DEFAULT 0,
  elapsed_ms INT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_doc_eval_page_id (page_id),
  KEY idx_doc_eval_grade_quality (grade, general_quality),
  KEY idx_doc_eval_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
